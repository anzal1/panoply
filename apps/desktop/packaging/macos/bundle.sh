#!/bin/bash
# Builds Panoply.app: the release binary, the shipped community modules (modules/shipped.txt), an Info.plist with
# LSUIElement false (Dock icon and app window; the command bar works from the hotkey), and an ad-hoc
# signature. Nothing is launched.
#
#   packaging/macos/bundle.sh                       build with the workspace release profile, then bundle
#   packaging/macos/bundle.sh --binary PATH         bundle an existing binary (no build)
#   packaging/macos/bundle.sh --modules DIR         bundle these built modules (tools/build-shipped-modules.sh
#                                                   output); without it the shipped ones are built here
#   packaging/macos/bundle.sh --sign "Developer ID Application: Name (TEAM)"   sign for distribution
#
# Output: apps/desktop/dist/Panoply.app. Notarization is a separate step (see packaging/README.md).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../../../.." && pwd)"
APPDIR="$ROOT/apps/desktop"
BINARY=""; SIGN="-"; MODULES=""
while [ $# -gt 0 ]; do
  case "$1" in
    --binary) BINARY="$2"; shift 2 ;;
    --sign) SIGN="$2"; shift 2 ;;
    --modules) MODULES="$(cd "$2" && pwd)"; shift 2 ;;
    *) echo "unknown option $1"; exit 2 ;;
  esac
done
if [ -z "$BINARY" ]; then
  (cd "$ROOT" && nice -n 10 cargo build --release -j4 -p panoply-desktop)
  BINARY="$ROOT/target/release/panoply-desktop"
fi
[ -x "$BINARY" ] || { echo "no binary at $BINARY"; exit 1; }
VERSION="$(sed -n 's/^version = "\(.*\)"/\1/p' "$ROOT/Cargo.toml" | head -1)"
APP="$APPDIR/dist/Panoply.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources/modules"
cp "$BINARY" "$APP/Contents/MacOS/Panoply"
sed "s/@VERSION@/$VERSION/g" "$HERE/Info.plist" > "$APP/Contents/Info.plist"
plutil -lint "$APP/Contents/Info.plist" >/dev/null
# The app icon (generated by tools/gen_app_icon.mjs, committed as Panoply.icns).
[ -f "$HERE/Panoply.icns" ] || { echo "missing $HERE/Panoply.icns"; exit 1; }
cp "$HERE/Panoply.icns" "$APP/Contents/Resources/Panoply.icns"
# License files and third-party notices travel inside the app (Resources/ is visible in Finder with
# Show Package Contents). THIRD-PARTY-NOTICES.md is generated: tools/notices/generate.py.
for f in LICENSE-MIT LICENSE-APACHE THIRD-PARTY-NOTICES.md; do
  [ -f "$ROOT/$f" ] || { echo "missing $ROOT/$f"; exit 1; }
  cp "$ROOT/$f" "$APP/Contents/Resources/$f"
done
# Community modules that ship with the app (modules/shipped.txt, never the learning examples): one
# folder each, manifest plus the compiled component, in Resources/modules where the catalog looks.
if [ -z "$MODULES" ]; then
  MODULES="$(mktemp -d)/modules"
  "$ROOT/tools/build-shipped-modules.sh" "$MODULES"
fi
mkdir -p "$APP/Contents/Resources/modules"
n=0
for m in "$MODULES"/*/; do
  [ -f "$m/module.toml" ] && [ -f "$m/module.wasm" ] || { echo "incomplete module folder $m"; exit 1; }
  cp -R "${m%/}" "$APP/Contents/Resources/modules/"
  n=$((n + 1))
done
[ "$n" -gt 0 ] || { echo "no modules to bundle in $MODULES"; exit 1; }
codesign --force --options runtime --sign "$SIGN" "$APP" >/dev/null
echo "Built $APP ($(du -sh "$APP" | cut -f1))"
