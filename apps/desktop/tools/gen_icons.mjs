// Emits src/icons_gen.rs: one standalone Lucide SVG (ISC license) per icon named below.
// Usage: node tools/gen_icons.mjs /path/to/node_modules/lucide-react/dist/esm/icons > src/icons_gen.rs
import { pathToFileURL } from "node:url";
import { join } from "node:path";
import { readFileSync } from "node:fs";

const dir = process.argv[2];
const names = [
  "search", "x", "house", "history", "folder-open", "folder", "upload", "chevron-right", "chevron-down",
  "check", "triangle-alert", "external-link", "undo-2", "shield-check", "lock", "arrow-right", "arrow-left",
  "smartphone", "monitor", "layout-grid", "file-text", "file-image", "file-audio", "file-video", "file-archive",
  "file-code", "file", "image", "film", "audio-lines", "type", "calculator", "camera", "code-xml", "id-card",
  "shield", "radio", "plus", "minus", "circle-check", "info", "scissors", "layers", "wand-sparkles", "hash",
  "copy", "refresh-cw", "package-open", "shrink", "expand", "settings-2", "puzzle", "rotate-cw", "files",
];
const attr = (o) =>
  Object.entries(o).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ");
const out = ["// GENERATED by tools/gen_icons.mjs from Lucide (ISC). Do not edit.\n", "pub(crate) const ICONS: &[(&str, &str)] = &[\n"];
for (const n of names) {
  let m;
  let file = n;
  for (let hops = 0; hops < 4; hops++) {
    const text = readFileSync(join(dir, file + ".mjs"), "utf8");
    const alias = text.match(/export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/);
    if (!alias) break;
    file = alias[1];
  }
  m = await import(pathToFileURL(join(dir, file + ".mjs")).href);
  const body = m.__iconData.node.map(([tag, a]) => `<${tag} ${attr(a)}/>`).join("");
  const w = n === "x" ? "2" : "1.75";
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
  out.push(`    (${JSON.stringify(n)}, ${JSON.stringify(svg)}),\n`);
}
out.push("];\n");
process.stdout.write(out.join(""));
