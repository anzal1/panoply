#!/usr/bin/env python3
"""Writes index.html of a HyperFrames project from frames.json (beats in, seconds out).
   python3 docs/launch/tools/assemble-index.py docs/launch/video [--stubs]
frames.json: {"id","w","h","bpm","gsap","frames":[{"id","name","src","beats","tail_beats"?}], "tail_s"?}
Frame starts are cumulative. A frame's data-duration is its beats (plus tail_beats) at the project's BPM."""
import json, os, sys
root = sys.argv[1]; stubs = '--stubs' in sys.argv
spec = json.load(open(os.path.join(root, 'frames.json')))
B = 60.0 / spec['bpm']; w, h = spec['w'], spec['h']
t = 0.0; hosts = []; total = 0.0
for i, f in enumerate(spec['frames']):
    beats = f['beats'] + f.get('tail_beats', 0)
    dur = round(beats * B, 5)
    hosts.append((i, f, round(t, 5), dur))
    t += f['beats'] * B
    total = t + f.get('tail_beats', 0) * B
total = round(total, 5)
spec['total_s'] = total
# Snap every frame boundary to the 60 fps grid, so the first sample of a frame is the frame the cue sheet names (beat 16 = frame 443, not 444).
import math
FPS = 60
def fl(x):
    return math.floor(x * 1e6) / 1e6
snapped = []
for k, (i, f, st, dur) in enumerate(hosts):
    sf = round(st * FPS)
    ef = round((st + dur) * FPS) if k + 1 == len(hosts) else round(hosts[k + 1][2] * FPS)
    snapped.append((i, f, fl(sf / FPS), fl((ef - sf) / FPS + 1e-9) if k + 1 == len(hosts) else fl((ef - sf) / FPS + 1e-9)))
orig_hosts = hosts
hosts = snapped
json.dump(spec, open(os.path.join(root, 'frames.json'), 'w'), indent=2)
rows = []
for i, f, st, dur in hosts:
    rows.append(f'''    <div id="host-{f['id']}" class="clip" data-composition-id="{f['id']}" data-composition-src="{f['src']}"
         data-start="{st}" data-duration="{dur}" data-track-index="{i + 1}" data-width="{w}" data-height="{h}"></div>''')
    p = os.path.join(root, f['src'])
    if stubs and not os.path.exists(p):
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, 'w').write(f'''<!doctype html>
<html><head><meta charset="UTF-8"></head><body>
<template>
  <style>
    #root {{ position: absolute; inset: 0; background: {spec.get('bg', '#0c0c0f')}; color: #ececf1; font: 700 96px Geist, system-ui; display: grid; place-items: center; }}
  </style>
  <div id="root" data-composition-id="{f['id']}" data-width="{w}" data-height="{h}"><div>{f['name']}</div></div>
  <script>
    const tl = gsap.timeline({{ paused: true }});
    window.__timelines["{f['id']}"] = tl;
  </script>
</template>
</body></html>
''')
snap_json = json.dumps({f['id']: round(st - orig, 6) for (i, f, st, dur), (_, _, orig, _) in zip(hosts, orig_hosts)})
html = f'''<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={w}, height={h}" />
    <script src="assets/vendor/gsap.min.js"></script>
    <script>window.__snap = {snap_json};</script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      @font-face {{ font-family: "Geist"; src: url("assets/fonts/Geist-Variable-latin.woff2") format("woff2"); font-weight: 100 900; }}
      @font-face {{ font-family: "Geist Mono"; src: url("assets/fonts/GeistMono-latin.woff2") format("woff2"); font-weight: 100 900; }}
      html, body {{ margin: 0; width: {w}px; height: {h}px; overflow: hidden; background: {spec.get('bg', '#0c0c0f')}; }}
    </style>
  </head>
  <body>
    <!-- Generated by docs/launch/tools/assemble-index.py from frames.json. Edit frames.json, not this file. {spec['bpm']} BPM, {len(hosts)} frames, {total}s. -->
    <div id="root" data-composition-id="{spec['id']}" data-start="0" data-duration="{total}" data-width="{w}" data-height="{h}">
{chr(10).join(rows)}
    </div>
    <script>
      const tl = gsap.timeline({{ paused: true }});
      window.__timelines["{spec['id']}"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
'''
open(os.path.join(root, 'index.html'), 'w').write(html)
print('wrote index.html', total, 's')
for i, f, st, dur in hosts: print(f"  {f['id']:<14} start {st:>9.5f}  dur {dur:>8.5f}  beats {f['beats']}+{f.get('tail_beats',0)}")
