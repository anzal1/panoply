#!/usr/bin/env python3
"""Emit src/icons_gen.rs: one standalone Lucide SVG per icon named in shared/utilities.json (plus search, x).

Source markup is the Lucide path data already extracted for the Tauri build
(../tauri/src/icons.generated.ts). Run only when utilities.json changes.
"""
import json, os, re
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "..", "tauri", "src", "icons.generated.ts")).read()
icons = json.loads(re.search(r"=\s*(\{.*\});", src, re.S).group(1))
tools = json.load(open(os.path.join(here, "..", "shared", "utilities.json")))
names = sorted({t["lucide"] for t in tools} | {"search", "x"})
wrap = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')
out = ["// GENERATED by gen_icons.py. Do not edit.\n", "pub const ICONS: &[(&str, &str)] = &[\n"]
for n in names:
    w = "2" if n in ("x",) else "1.75"
    out.append('    ({}, {}),\n'.format(json.dumps(n), json.dumps(wrap.format(w=w, body=icons[n]))))
out.append("];\n")
open(os.path.join(here, "src", "icons_gen.rs"), "w").write("".join(out))
print(len(names), "icons")
