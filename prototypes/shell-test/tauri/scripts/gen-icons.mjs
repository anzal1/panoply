// Tree-shakes Lucide: emits only the icons named in shared/utilities.json (plus UI glyphs)
// as inline SVG markup into src/icons.generated.ts. No CDN, no runtime icon library.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tools = JSON.parse(readFileSync(join(root, '..', 'shared', 'utilities.json'), 'utf8'));
const names = new Set(tools.map((t) => t.lucide));
['search', 'x'].forEach((n) => names.add(n));

const pascal = (s) => s.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
const esm = join(root, 'node_modules', 'lucide', 'dist', 'esm');
const iconDir = join(esm, 'icons');
// Lucide renames icons and keeps the old names as aliases: resolve through the alias table.
const aliasSrc = readFileSync(join(esm, 'iconsAndAliases.mjs'), 'utf8');
const aliasFile = (name) => {
  const P = pascal(name);
  const re = new RegExp(`export \\{([^}]*\\bas ${P}\\b[^}]*)\\} from '\\./icons/([^']+)\\.mjs'`);
  const m = aliasSrc.match(re);
  return m ? m[2] : null;
};

const attr = (o) =>
  Object.entries(o)
    .filter(([k]) => k !== 'key')
    .map(([k, v]) => `${k}="${v}"`)
    .join(' ');

// Names in utilities.json that this lucide release no longer ships.
const FALLBACK = { 'files-merge': 'combine' };
const LV = JSON.parse(readFileSync(join(root, 'node_modules', 'lucide', 'package.json'), 'utf8')).version;
const out = {};
for (const name of [...names].sort()) {
  let file = join(iconDir, `${name}.mjs`);
  if (!existsSync(file)) {
    const real = aliasFile(name);
    const sub = FALLBACK[name];
    if (!real && !sub) throw new Error(`lucide icon not found: ${name}`);
    if (!real) console.log(`icons: "${name}" is absent from lucide ${LV}, using "${sub}"`);
    file = join(iconDir, `${real ?? sub}.mjs`);
  }
  const src = readFileSync(file, 'utf8');
  const m = src.match(/const \w+ = (\[[\s\S]*?\n\]);/);
  if (!m) throw new Error(`cannot parse ${name}`);
  const nodes = new Function(`return ${m[1]}`)();
  out[name] = nodes.map(([tag, a]) => `<${tag} ${attr(a)}/>`).join('');
}

const body =
  '// GENERATED by scripts/gen-icons.mjs from the lucide package. Do not edit.\n' +
  `export const ICONS: Record<string, string> = ${JSON.stringify(out)};\n`;
writeFileSync(join(root, 'src', 'icons.generated.ts'), body);
console.log(`icons: ${Object.keys(out).length} -> src/icons.generated.ts (${body.length} bytes)`);
