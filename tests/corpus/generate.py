def needs(entry: dict) -> list:
    missing = []
    for r in entry.get("requires", []):
        if r == "ffmpeg" and not (have("ffmpeg") and have("ffprobe")):
            missing.append("ffmpeg and ffprobe on PATH")
        if r == "pillow" and importlib.util.find_spec("PIL") is None:
            missing.append("Pillow (pip install pillow)")
    return missing


def build(entry: dict, args) -> tuple:
    path = C.cache_path(entry["kind"], entry)
    name = entry["generator"]
    if name not in GENERATORS:
        return "fail", f"no generator named {name}"
    miss = needs(entry)
    if miss:
        return "skip", "needs " + ", ".join(miss)
    pinned = entry["sha256"]
    stable = name in STABLE
    if os.path.exists(path) and not args.force:
        if stable and pinned:
            if C.sha256_file(path) == pinned:
                return "cached", ""
        elif os.path.getsize(path) > 0:
            return "cached", ""
    if args.check:
        return "fail", "missing or changed"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    # Keep the real extension last: ffmpeg picks the muxer from it.
    tmp = os.path.join(os.path.dirname(path), ".part-" + os.path.basename(path))
    t0 = time.time()
    try:
        GENERATORS[name](tmp)
        os.replace(tmp, path)
    except Exception as e:  # keep going so one bad generator does not hide the rest
        if os.path.exists(tmp):
            os.remove(tmp)
        return "fail", f"{type(e).__name__}: {e}"
    size = os.path.getsize(path)
    note = f"{C.human(size)} in {time.time() - t0:.1f}s"
    if stable:
        digest = C.sha256_file(path)
        if pinned and digest != pinned:
            return "fail", f"not deterministic: sha256 {digest[:16]} differs from pinned {pinned[:16]}"
        if not pinned and args.fill:
            C.fill_hash(entry["kind"], entry["id"], digest, size)
            return "filled", note
    elif args.fill and entry["size"] != size:
        # Not byte-stable, but record the size we saw so the harness can report it.
        pass
    return "ok", note


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--kind", help="comma list of: " + ", ".join(C.KINDS))
    ap.add_argument("--id", action="append")
    ap.add_argument("--tier", choices=list(TIER_ORDER), default="default")
    ap.add_argument("--force", action="store_true", help="rebuild even if the file exists")
    ap.add_argument("--check", action="store_true", help="verify existing files, build nothing")
    ap.add_argument("--fill", action="store_true", help="pin sha256 of byte-stable files that lack one")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()

    kinds = tuple(args.kind.split(",")) if args.kind else C.KINDS
    allowed = [t for t, n in TIER_ORDER.items() if n <= TIER_ORDER[args.tier]]
    entries = [e for e in C.select(C.load_all(kinds), ids=args.id, tiers=tuple(allowed)) if e.get("source") == "generated"]

    if args.list:
        for e in entries:
            flag = "stable" if e["generator"] in STABLE else "tool"
            print(f"{e['kind']:7} {e['id']:34} {e['tier']:8} {flag:7} {e['generator']}")
        print(f"\n{len(entries)} generated entries up to tier {args.tier}")
        return 0

    counts: dict = {}
    for e in entries:
        status, msg = build(e, args)
        counts[status] = counts.get(status, 0) + 1
        if status != "cached":
            print(f"{status:7} {e['kind']:6} {e['id']}  {msg}", flush=True)
    print("\n" + ", ".join(f"{v} {k}" for k, v in sorted(counts.items())))
    return 1 if counts.get("fail") else 0


if __name__ == "__main__":
    sys.exit(main())
