class PdfOut:
    """A tiny streaming PDF writer: objects go to disk as they are made, xref comes last."""

    def __init__(self, path: str):
        self.f = open(path, "wb")
        self.offsets: dict = {}
        self.pos = 0
        self.write(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")

    def write(self, b: bytes):
        self.f.write(b)
        self.pos += len(b)

    def obj(self, num: int, body: bytes):
        self.offsets[num] = self.pos
        self.write(b"%d 0 obj\n" % num + body + b"\nendobj\n")

    def stream(self, num: int, dict_items: bytes, data: bytes):
        self.offsets[num] = self.pos
        self.write(b"%d 0 obj\n<< %s /Length %d >>\nstream\n" % (num, dict_items, len(data)))
        self.write(data)
        self.write(b"\nendstream\nendobj\n")

    def stream_begin(self, num: int, dict_items: bytes, length: int):
        self.offsets[num] = self.pos
        self.write(b"%d 0 obj\n<< %s /Length %d >>\nstream\n" % (num, dict_items, length))

    def stream_end(self):
        self.write(b"\nendstream\nendobj\n")

    def finish(self, root: int, info: int = None):
        size = max(self.offsets) + 1
        start = self.pos
        self.write(b"xref\n0 %d\n" % size)
        self.write(b"0000000000 65535 f \n")
        for n in range(1, size):
            self.write(b"%010d 00000 n \n" % self.offsets[n])
        trailer = b"trailer\n<< /Size %d /Root %d 0 R" % (size, root)
        if info:
            trailer += b" /Info %d 0 R" % info
        self.write(trailer + b" >>\nstartxref\n%d\n%%%%EOF\n" % start)
        self.f.close()


def _text_content(lines, x=72, y=720, size=12, leading=16) -> bytes:
    out = [b"BT /F1 %d Tf %d %d Td %d TL" % (size, x, y, leading)]
    for ln in lines:
        esc = ln.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
        out.append(b"(" + esc.encode("latin-1", "replace") + b") '")
    out.append(b"ET")
    return b"\n".join(out)


def _simple_pdf(path: str, pages, compress: bool = False, info_title: str = None):
    """pages: list of dicts with w, h, rotate (0/90/180/270), lines. Fixed object layout."""
    pdf = PdfOut(path)
    n = len(pages)
    kids = " ".join("%d 0 R" % (4 + 2 * i) for i in range(n))
    pdf.obj(1, b"<< /Type /Catalog /Pages 2 0 R >>")
    pdf.obj(2, ("<< /Type /Pages /Kids [%s] /Count %d >>" % (kids, n)).encode())
    pdf.obj(3, b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    for i, p in enumerate(pages):
        pg, ct = 4 + 2 * i, 5 + 2 * i
        rot = b" /Rotate %d" % p.get("rotate", 0) if p.get("rotate") else b""
        pdf.obj(pg, b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %s %s]%s /Contents %d 0 R /Resources << /Font << /F1 3 0 R >> >> >>"
                % (str(p["w"]).encode(), str(p["h"]).encode(), rot, ct))
        content = p.get("raw") or _text_content(p["lines"], y=int(p["h"]) - 72)
        if compress:
            pdf.stream(ct, b"/Filter /FlateDecode", zlib.compress(content, 6))
        else:
            pdf.stream(ct, b"", content)
    info = None
    if info_title:
        info = 4 + 2 * n
        pdf.obj(info, b"<< /Title (%s) /Producer (Panoply test corpus) >>" % info_title.encode())
    pdf.finish(1, info)


def _words(rng: random.Random, n: int) -> str:
    vocab = "page file memory stream budget module preview render cache queue decode encode tile band edge header footer table".split()
    return " ".join(rng.choice(vocab) for _ in range(n))


def _base_doc_bytes(tmpdir: str, pages: int = 40) -> bytes:
    rng = random.Random(7)
    spec = []
    for i in range(pages):
        lines = ["Panoply corpus base document, page %d of %d" % (i + 1, pages), ""]
        lines += [_words(rng, 10) for _ in range(40)]
        spec.append(dict(w=612, h=792, lines=lines))
    p = os.path.join(tmpdir, "base.pdf")
    _simple_pdf(p, spec, compress=True, info_title="Panoply corpus base document")
    with open(p, "rb") as f:
        return f.read()


