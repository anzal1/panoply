@gen("pdf_scanned_skewed")
def pdf_scanned_skewed(path: str):
    from PIL import Image, ImageDraw, ImageFont  # noqa: PLC0415

    W, H = 1240, 1754  # A4 at 150 dpi
    rng = random.Random(3)
    font = ImageFont.load_default()
    pages = []

    def text_page(punch: bool) -> Image.Image:
        im = Image.new("L", (W, H), 245)
        d = ImageDraw.Draw(im)
        y = 140
        for _ in range(38):
            d.text((130, y), _words(rng, 11), fill=25, font=font)
            y += 38
        if punch:
            d.ellipse((24, 840, 64, 880), fill=0)
        rot = im.rotate(2.3, resample=Image.BICUBIC, fillcolor=250)
        px = rot.load()
        for _ in range(900):  # speckle
            px[rng.randrange(W), rng.randrange(H)] = rng.randrange(120, 200)
        return rot

    def near_blank(mark: bool, edge: bool) -> Image.Image:
        im = Image.new("L", (W, H), 247)
        d = ImageDraw.Draw(im)
        if mark:
            d.line((300, 900, 360, 915), fill=170, width=2)  # faint pencil mark
        if edge:
            d.rectangle((0, 0, 6, H), fill=60)  # scanner edge shadow
        return im

    images = [text_page(False), near_blank(True, True), text_page(True), near_blank(False, True)]
    import io  # noqa: PLC0415

    jpegs = []
    for im in images:
        b = io.BytesIO()
        im.save(b, "JPEG", quality=68)
        jpegs.append(b.getvalue())
    pdf = PdfOut(path)
    n = len(jpegs)
    pdf.obj(1, b"<< /Type /Catalog /Pages 2 0 R >>")
    pdf.obj(2, ("<< /Type /Pages /Kids [%s] /Count %d >>" % (" ".join("%d 0 R" % (3 + 3 * i) for i in range(n)), n)).encode())
    for i, jb in enumerate(jpegs):
        pg, ct, im = 3 + 3 * i, 4 + 3 * i, 5 + 3 * i
        pdf.obj(pg, b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents %d 0 R /Resources << /XObject << /Im0 %d 0 R >> >> >>" % (ct, im))
        pdf.stream(ct, b"", b"q 595 0 0 842 0 0 cm /Im0 Do Q")
        pdf.stream(im, b"/Type /XObject /Subtype /Image /Width %d /Height %d /ColorSpace /DeviceGray /BitsPerComponent 8 /Filter /DCTDecode" % (W, H), jb)
    pdf.finish(1)


