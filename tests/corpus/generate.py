@gen("png_16bit_rgba", stable=True)
def png_16bit_rgba(path: str):
    w, h = 1024, 512

    def rows():
        for y in range(h):
            g = y * 65535 // (h - 1)
            buf = bytearray()
            for x in range(w):
                r = x * 65535 // (w - 1)
                b = (x + y) * 65535 // (w + h - 2)
                a = 65535 - (x * 32767 // (w - 1))
                buf += struct.pack(">4H", r, g, b, a)
            yield bytes(buf)

    mk_png(path, w, h, 6, 16, rows())


@gen("png_display_p3", stable=True)
def png_display_p3(path: str):
    w, h = 640, 480
    prim = [(255, 0, 0), (0, 255, 0), (0, 0, 255), (255, 255, 0), (0, 255, 255), (255, 0, 255)]

    def rows():
        for y in range(h):
            if y < 320:
                band = prim[y * 6 // 320]
                row = bytearray()
                for x in range(w):
                    k = x / (w - 1)
                    row += bytes(round(255 - k * (255 - c)) for c in band)  # white to saturated P3 primary
                yield bytes(row)
            else:
                row = bytearray()
                for x in range(w):
                    v = round(x * 255 / (w - 1))
                    row += bytes((v, v, v))
                yield bytes(row)

    icc = zlib.compress(icc_display_p3(), 9)
    mk_png(path, w, h, 2, 8, rows(), extra_chunks=[(b"iCCP", b"Display P3\0\0" + icc)])


@gen("png_huge_400mp", stable=True)
def png_huge_400mp(path: str):
    side = 20000
    base = bytes((x * 7 + (x >> 4) * 3) & 0xFF for x in range(side + 256))

    def rows():
        for y in range(side):
            off = (y * 5) % 256
            yield base[off: off + side]

    mk_png(path, side, side, 0, 8, rows(), level=1)


def _tiff(path: str, width: int, height: int, spp: int, bits: int, photometric: int, data: bytes, ink_set: int = None):
    entries = []

    def add(tag, typ, count, value):
        entries.append((tag, typ, count, value))

    ifd_count = 12 if ink_set else 11
    ifd_size = 2 + 12 * ifd_count + 4
    off_bps = 8 + ifd_size
    off_res = off_bps + 2 * spp
    off_data = off_res + 16
    add(256, 4, 1, width)
    add(257, 4, 1, height)
    add(258, 3, spp, off_bps if spp > 2 else bits)
    add(259, 3, 1, 1)
    add(262, 3, 1, photometric)
    add(273, 4, 1, off_data)
    add(277, 3, 1, spp)
    add(278, 4, 1, height)
    add(279, 4, 1, len(data))
    add(282, 5, 1, off_res)
    add(283, 5, 1, off_res + 8)
    if ink_set:
        add(332, 3, 1, ink_set)
    entries.sort()
    out = b"II*\0" + struct.pack("<I", 8) + struct.pack("<H", len(entries))
    for tag, typ, count, value in entries:
        if typ == 3 and count == 1:
            out += struct.pack("<HHIHH", tag, typ, count, value, 0)
        else:
            out += struct.pack("<HHII", tag, typ, count, value)
    out += struct.pack("<I", 0)
    out += struct.pack("<%dH" % spp, *([bits] * spp))
    out += struct.pack("<IIII", 300, 1, 300, 1)
    assert len(out) == off_data, (len(out), off_data)
    with open(path, "wb") as f:
        f.write(out + data)


@gen("tiff_cmyk", stable=True)
def tiff_cmyk(path: str):
    w, h = 1024, 768
    rows = bytearray()
    for y in range(h):
        for x in range(w):
            c = x * 255 // (w - 1)
            m = y * 255 // (h - 1)
            yy = ((x + y) * 255) // (w + h - 2)
            k = 40 if (x // 64 + y // 64) % 2 else 0
            rows += bytes((c, m, yy, k))
    _tiff(path, w, h, 4, 8, 5, bytes(rows), ink_set=1)


@gen("tiff_16bit_rgb", stable=True)
def tiff_16bit_rgb(path: str):
    w, h = 800, 600
    rows = bytearray()
    for y in range(h):
        for x in range(w):
            rows += struct.pack("<3H", x * 65535 // (w - 1), y * 65535 // (h - 1), (x * y * 65535) // ((w - 1) * (h - 1)))
    _tiff(path, w, h, 3, 16, 2, bytes(rows))


@gen("jpeg_cmyk")
def jpeg_cmyk(path: str):
    from PIL import Image  # noqa: PLC0415

    w, h = 640, 480
    c = Image.linear_gradient("L").resize((w, h))
    m = c.rotate(90, expand=True).resize((w, h))
    yb = Image.new("L", (w, h), 40)
    k = Image.linear_gradient("L").resize((w, h)).point(lambda v: v // 6)
    Image.merge("CMYK", (c, m, yb, k)).save(path, "JPEG", quality=88)
    with open(path, "rb") as f:
        head = f.read(4096)
    assert b"Adobe" in head, "no Adobe marker"
    with Image.open(path) as im:
        assert im.mode == "CMYK", im.mode


