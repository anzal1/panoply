def _top_level_boxes(path: str) -> list:
    boxes = []
    with open(path, "rb") as f:
        pos = 0
        size = os.path.getsize(path)
        while pos + 8 <= size:
            f.seek(pos)
            n, name = struct.unpack(">I4s", f.read(8))
            if n == 1:
                n = struct.unpack(">Q", f.read(8))[0]
            elif n == 0:
                n = size - pos
            boxes.append((name.decode("latin-1"), pos, n))
            pos += n
    return boxes


