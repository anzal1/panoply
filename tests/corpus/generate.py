@gen("pdf_junk_prefix_bitflip", stable=True)
def pdf_junk_prefix_bitflip(path: str):
    with tempfile.TemporaryDirectory() as t:
        data = bytearray(_base_doc_bytes(t))
    rng = random.Random(11)
    marks = []
    i = 0
    while True:
        i = data.find(b"stream\n", i)
        if i < 0:
            break
        marks.append(i + 7)
        i += 7
    for k in rng.sample(marks[5:], 5):
        data[k + rng.randrange(10, 100)] ^= 1 << rng.randrange(8)
    junk = b"".join(b"Received: by corpus.example (Panoply) id %05d\r\n" % n for n in range(6))
    with open(path, "wb") as f:
        f.write(junk + bytes(data))


def _image_pdf(path: str, pages: int, image_bytes: int = 1 << 20, side: int = 1024):
    """A PDF of `pages` full-page gray images, `image_bytes` each, uncompressed and streamed."""
    rng = random.Random(5)
    block = rng.randbytes(image_bytes)
    # smooth it so viewers show something, but keep it incompressible enough to stay near N MB
    pdf = PdfOut(path)
    kids = " ".join("%d 0 R" % (3 + 3 * i) for i in range(pages))
    pdf.obj(1, b"<< /Type /Catalog /Pages 2 0 R >>")
    pdf.obj(2, ("<< /Type /Pages /Kids [%s] /Count %d >>" % (kids, pages)).encode())
    for i in range(pages):
        pg, ct, im = 3 + 3 * i, 4 + 3 * i, 5 + 3 * i
        pdf.obj(pg, b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents %d 0 R /Resources << /XObject << /Im0 %d 0 R >> >> >>" % (ct, im))
        pdf.stream(ct, b"", b"q 612 0 0 792 0 0 cm /Im0 Do Q")
        pdf.stream_begin(im, b"/Type /XObject /Subtype /Image /Width %d /Height %d /ColorSpace /DeviceGray /BitsPerComponent 8" % (side, image_bytes // side), image_bytes)
        pdf.write(struct.pack(">I", i) + block[4:])
        pdf.stream_end()
    pdf.finish(1)


