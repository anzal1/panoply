def _write_wav(path: str, samples_by_channel, rate: int, sampwidth: int):
    with wave.open(path, "wb") as w:
        w.setnchannels(len(samples_by_channel))
        w.setsampwidth(sampwidth)
        w.setframerate(rate)
        n = len(samples_by_channel[0])
        frames = bytearray()
        for i in range(n):
            for ch in samples_by_channel:
                v = ch[i]
                if sampwidth == 2:
                    frames += struct.pack("<h", v)
                else:
                    frames += struct.pack("<i", v)[:3]
        w.writeframes(bytes(frames))


