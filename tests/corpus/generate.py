def have(tool: str) -> bool:
    return shutil.which(tool) is not None


def run(cmd: list, **kw):
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, **kw)
    if r.returncode != 0:
        raise RuntimeError(f"{cmd[0]} failed ({r.returncode}): {r.stderr.strip()[-600:]}")
    return r


def ffmpeg(*args: str):
    return run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *args])


def probe(path: str) -> dict:
    cmd = ["ffprobe", "-v", "error", "-show_format", "-show_streams", "-of", "json", path]
    return json.loads(run(cmd).stdout)


def mk_png(path: str, width: int, height: int, color_type: int, bit_depth: int, rows, extra_chunks=(), level: int = 6):
    """Write a PNG. `rows` yields raw scanline bytes without the filter byte."""

    def chunk(t: bytes, d: bytes) -> bytes:
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    comp = zlib.compressobj(level)
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, bit_depth, color_type, 0, 0, 0)))
        for t, d in extra_chunks:
            f.write(chunk(t, d))
        buf = bytearray()
        for row in rows:
            buf += b"\x00" + row
            if len(buf) > 1 << 20:
                f.write(chunk(b"IDAT", comp.compress(bytes(buf))))
                buf.clear()
        tail = comp.compress(bytes(buf)) + comp.flush()
        f.write(chunk(b"IDAT", tail))
        f.write(chunk(b"IEND", b""))


def icc_display_p3() -> bytes:
    """A small matrix and TRC ICC v2 profile for Display P3 (D50 adapted colorants, sRGB curve)."""

    def s15(x):
        return struct.pack(">i", int(round(x * 65536)))

    def xyz(x, y, z):
        return b"XYZ \0\0\0\0" + s15(x) + s15(y) + s15(z)

    def text(s):
        return b"text\0\0\0\0" + s.encode("ascii") + b"\0"

    def desc(s):
        a = s.encode("ascii") + b"\0"
        return b"desc\0\0\0\0" + struct.pack(">I", len(a)) + a + struct.pack(">II", 0, 0) + struct.pack(">HB", 0, 0) + b"\0" * 67

    def srgb(v):
        return v * 12.92 if v <= 0.0031308 else 1.055 * (v ** (1 / 2.4)) - 0.055

    # TRC from display code value to linear light is the inverse: samples of the sRGB EOTF.
    def eotf(v):
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4

    n = 1024
    curve = b"curv\0\0\0\0" + struct.pack(">I", n) + b"".join(struct.pack(">H", round(65535 * eotf(i / (n - 1)))) for i in range(n))
    tags = [
        (b"desc", desc("Display P3")),
        (b"cprt", text("Public domain. Generated by the Panoply test corpus.")),
        (b"wtpt", xyz(0.9642, 1.0, 0.8249)),
        (b"rXYZ", xyz(0.51512, 0.2412, -0.00105)),
        (b"gXYZ", xyz(0.29198, 0.69225, 0.04189)),
        (b"bXYZ", xyz(0.1571, 0.06657, 0.78407)),
        (b"rTRC", curve),
        (b"gTRC", None),
        (b"bTRC", None),
    ]
    body = b""
    table = []
    offset = 128 + 4 + 12 * len(tags)
    shared = None
    for sig, data in tags:
        if data is None:  # gTRC and bTRC share the red curve's bytes
            table.append((sig, shared[0], shared[1]))
            continue
        pad = (-len(data)) % 4
        table.append((sig, offset + len(body), len(data)))
        if sig == b"rTRC":
            shared = (offset + len(body), len(data))
        body += data + b"\0" * pad
    total = offset + len(body)
    header = struct.pack(">I", total) + b"\0\0\0\0" + struct.pack(">I", 0x02400000) + b"mntrRGB XYZ "
    header += struct.pack(">6H", 2026, 1, 1, 0, 0, 0) + b"acsp" + b"APPL" + b"\0" * 4 + b"\0" * 4 + b"\0" * 4 + b"\0" * 8 + b"\0" * 4
    header += s15(0.9642) + s15(1.0) + s15(0.8249) + b"PNPL" + b"\0" * 16 + b"\0" * 28
    assert len(header) == 128, len(header)
    tbl = struct.pack(">I", len(tags)) + b"".join(struct.pack(">4sII", s, o, z) for s, o, z in table)
    return header + tbl + body


