# Byte-stable generators: pure Python, fixed seeds. Their hashes are pinned in the manifests.
STABLE: set = set()


def gen(name: str, stable: bool = False):
    def deco(fn):
        GENERATORS[name] = fn
        if stable:
            STABLE.add(name)
        return fn

    return deco


